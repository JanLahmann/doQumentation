import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

// Sidebar item type derived from the PUBLIC SidebarsConfig, avoiding the deep
// import of '@docusaurus/.../lib/sidebars/types' (unresolvable under the package's
// exports map → TS2307). A sidebar value is either an item array or a categories
// shorthand object; we want the array's element type.
type SidebarValue = SidebarsConfig[string];
type SidebarItemConfig = SidebarValue extends readonly (infer T)[]
  ? T
  : Extract<SidebarValue, readonly unknown[]>[number];

// Sidebar links to static files (the contributor-licence PDFs under
// /docs/open-source/) are not routes, so the broken-link check flags them and
// client-side navigation would 404. `pathname://` makes them plain links.
function staticFileLinks(items: SidebarItemConfig[]): SidebarItemConfig[] {
  return items.map((item) => {
    if (typeof item !== 'object' || !('type' in item)) return item;
    if (item.type === 'link') {
      const link = item as {href: string; [k: string]: unknown};
      if (/^\/[^#?]*\.(pdf|zip|ipynb|py|txt|csv|json)$/i.test(link.href)) {
        return {...link, href: `pathname://${link.href}`} as SidebarItemConfig;
      }
      return item;
    }
    if (item.type === 'category') {
      const cat = item as {items?: SidebarItemConfig[]; [k: string]: unknown};
      return (cat.items ? {...cat, items: staticFileLinks(cat.items)} : item) as SidebarItemConfig;
    }
    return item;
  });
}

// Import generated sidebar structures from sync-content.py (written to
// .generated/ so they don't clutter the repo root; gitignored).
// Falls back to autogenerated/empty if sync hasn't run yet.
let tutorialItems: SidebarItemConfig[];
try {
  tutorialItems = staticFileLinks(require('./.generated/sidebar-generated.json'));
} catch {
  tutorialItems = [{type: 'autogenerated', dirName: 'tutorials'}];
}

// One sidebar per guide subsite, as on IBM's site: {sidebarId: items}, the
// main "Guides" sidebar (guidesSidebar) first. See generate_guides_sidebar in
// scripts/sync-content.py.
let guideSidebars: Record<string, SidebarItemConfig[]>;
try {
  const raw = require('./.generated/sidebar-guides.json') as
    | Record<string, SidebarItemConfig[]>
    | SidebarItemConfig[];
  guideSidebars = Array.isArray(raw) ? {} : raw;
} catch {
  guideSidebars = {};
}
for (const id of Object.keys(guideSidebars)) {
  guideSidebars[id] = staticFileLinks(guideSidebars[id]);
}

let courseItems: SidebarItemConfig[];
try {
  courseItems = staticFileLinks(require('./.generated/sidebar-courses.json'));
} catch {
  courseItems = [];
}

let moduleItems: SidebarItemConfig[];
try {
  moduleItems = staticFileLinks(require('./.generated/sidebar-modules.json'));
} catch {
  moduleItems = [];
}

let addonItems: SidebarItemConfig[];
try {
  addonItems = staticFileLinks(require('./.generated/sidebar-addons.json'));
} catch {
  addonItems = [];
}

const sidebars: SidebarsConfig = {
  tutorialsSidebar: [
    {
      type: 'link',
      label: 'Home',
      href: '/',
    },
    {
      type: 'category',
      label: 'Tutorials',
      collapsed: true,
      link: {type: 'doc', id: 'tutorials/index'},
      items: tutorialItems,
    },
    // The guides have their own sidebars (below); this entry leads to them.
    ...(guideSidebars.guidesSidebar
      ? [{type: 'link' as const, href: '/guides', label: 'Guides', className: 'dq-subsite-enter'}]
      : []),
    ...(courseItems.length > 0
      ? [
          {
            type: 'category' as const,
            label: 'Courses',
            collapsed: true,
            items: courseItems,
          },
        ]
      : []),
    ...(moduleItems.length > 0
      ? [
          {
            type: 'category' as const,
            label: 'Modules',
            collapsed: true,
            items: moduleItems,
          },
        ]
      : []),
    /* API Reference + Settings are in the navbar — not duplicated here */
  ],
  ...guideSidebars,
  // Qiskit Addons live in their own sidebar so the pages are still built and
  // have working navigation when visited by direct URL, but they do NOT appear
  // in the main tutorialsSidebar or the navbar. Re-enable by adding a navbar
  // entry in docusaurus.config.ts and/or splicing the category back into
  // tutorialsSidebar above.
  ...(addonItems.length > 0
    ? {
        qiskitAddonsSidebar: [
          {
            type: 'category' as const,
            label: 'Qiskit Addons',
            collapsed: false,
            link: {type: 'doc' as const, id: 'qiskit-addons/index'},
            items: addonItems,
          },
        ],
      }
    : {}),
  // Workshop notebooks — accessible via /workshop/{name} but not in navbar.
  // Instructors add notebooks to docs/workshop/ for hands-on sessions.
  // generated-index makes the category header clickable (shows card listing)
  // without a separate "Workshop Notebooks" entry in the sidebar.
  workshopSidebar: [
    {
      type: 'category' as const,
      label: 'Workshop Notebooks',
      collapsed: false,
      link: {
        type: 'generated-index' as const,
        slug: '/workshop',
        title: 'Workshop Notebooks',
        description: 'Community workshop notebooks for hands-on sessions. Not part of the official IBM Quantum documentation.',
      },
      items: [{type: 'autogenerated' as const, dirName: 'workshop'}],
    },
  ],
};

export default sidebars;

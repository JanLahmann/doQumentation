#!/usr/bin/env python3
"""Refresh src/data/learning-paths.json from IBM Quantum Learning.

IBM keeps its learning paths in its web app, not in the open-source docs
(Qiskit/documentation), so sync-content.py never sees them. The learning
page loads them as JSON from IBM_URL; this script reads that, maps every
step to our doc id and rewrites the data file that plugins/course-catalogue
turns into /learning-paths. sync-upstream.yml runs it every week, so a
change at IBM arrives with the content sync PR.

Never fails the sync:
  - IBM unreachable or the JSON changed shape: a warning, the file is kept.
  - A path we have no translated name for (PATH_IDS): a warning, the path
    is left out until someone adds it here and to src/components/LearningPaths.
  - A step whose page is not in docs/: a warning, the step is kept (the
    plugin drops it from the build until the page exists).

    python3 scripts/sync-learning-paths.py           # rewrite the file
    python3 scripts/sync-learning-paths.py --check   # exit 1 if it would change
"""

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "src" / "data" / "learning-paths.json"
DOCS = ROOT / "docs"
IBM_URL = "https://quantum.cloud.ibm.com/endpoints-docs-learning/api/learning-paths/en"
SOURCE = "https://quantum.cloud.ibm.com/learning"

# IBM's path slug -> our id (the key of its translated name and description
# in src/components/LearningPaths). A new IBM path needs an entry here.
PATH_IDS = {
    "introduction-to-quantum": "introduction",
    "optimization": "optimization",
    "data-science": "data-science",
    "physics-and-chemistry": "physics-chemistry",
    "quantum-algorithm-development": "algorithms",
    "qise": "qise",
}
# Order of the paths on our page.
ORDER = ["introduction", "optimization", "data-science", "physics-chemistry", "algorithms", "qise"]
# IBM's level slugs end in -i, -ii, -iii.
LEVELS = {"i": "beginner", "ii": "intermediate", "iii": "advanced"}

COMMENT = (
    "Generated by scripts/sync-learning-paths.py from IBM Quantum Learning's learning paths "
    "(https://quantum.cloud.ibm.com/learning, 'Multi-resource learning paths'): the order of the "
    "steps and IBM's time estimates. Do not edit by hand; sync-upstream.yml refreshes it weekly. "
    "A step is a doc id under docs/ (a course or module overview id gets the course's pages for "
    "progress); `ibm` is the path's ?modal= slug on IBM's page. Path names and descriptions are "
    "translated in src/components/LearningPaths. plugins/course-catalogue resolves the steps "
    "into /learning-paths."
)


def warn(msg: str) -> None:
    print(f"::warning::sync-learning-paths: {msg}")


def doc_id(href: str) -> str:
    """IBM link -> our doc id: /docs/tutorials/x -> tutorials/x,
    /learning/courses/x -> learning/courses/x/index."""
    path = href.split("?")[0].strip("/")
    if path.startswith("docs/"):
        path = path[len("docs/"):]
    if (DOCS / path / "index.mdx").exists():
        return f"{path}/index"
    if not (DOCS / f"{path}.mdx").exists():
        warn(f"step {href} has no page under docs/ (yet)")
    return path


def level(slug: str, materials: list, top: str) -> dict:
    steps = []
    for m in materials:
        href = m.get("href") or ""
        if not href or "hours" not in m:
            raise ValueError(f"step without href or hours in {slug}")
        steps.append({"id": doc_id(href), "hours": m["hours"]})
    suffix = slug.rsplit("-", 1)[-1] if slug != top else None
    return {
        "level": LEVELS.get(suffix) if suffix else None,
        "hours": round(sum(s["hours"] for s in steps), 2),
        "ibm": slug if slug == top else f"{top}/{slug}",
        "steps": steps,
    }


def convert(ibm: list) -> dict:
    paths = []
    for p in ibm:
        our = PATH_IDS.get(p["slug"])
        if not our:
            warn(f"new IBM path '{p['slug']}': add it to PATH_IDS and src/components/LearningPaths to show it")
            continue
        if p.get("materials"):
            levels = [level(p["slug"], p["materials"], p["slug"])]
        else:
            levels = [level(c["slug"], c["materials"], p["slug"]) for c in p.get("paths", [])]
        if not levels:
            raise ValueError(f"path {p['slug']} has no materials and no levels")
        paths.append({"id": our, "levels": levels})
    paths.sort(key=lambda p: ORDER.index(p["id"]))
    return {"_comment": COMMENT, "source": SOURCE, "paths": paths}


def main() -> int:
    check = "--check" in sys.argv
    try:
        # IBM answers 403 to urllib's default User-Agent.
        req = urllib.request.Request(IBM_URL, headers={"User-Agent": "doQumentation-sync (+https://doqumentation.org)"})
        with urllib.request.urlopen(req, timeout=30) as r:
            data = convert(json.load(r))
    except Exception as e:  # network, JSON or shape: keep what we have
        warn(f"could not refresh from {IBM_URL} ({e}); keeping {DATA.name}")
        return 0
    new = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    old = DATA.read_text(encoding="utf-8") if DATA.exists() else ""
    if new == old:
        print("learning paths unchanged")
        return 0
    if check:
        print("learning paths changed at IBM; run scripts/sync-learning-paths.py")
        return 1
    DATA.write_text(new, encoding="utf-8")
    print(f"learning paths updated: {sum(len(l['steps']) for p in data['paths'] for l in p['levels'])} steps")
    return 0


if __name__ == "__main__":
    sys.exit(main())
